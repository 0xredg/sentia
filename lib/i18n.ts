export type TranslationKey = keyof typeof translations.en;

export function translate(
  locale: Locale,
  key: TranslationKey,
  values: Record<string, string | number> = {},
) {
  const value = translations[locale][key] ?? translations.en[key];

  return typeof value === "function" ? value(values) : value;
}

export function getIntlLocale(locale: Locale) {
  return locale === "ko" ? "ko-KR" : "en";
}

const serverErrorKeys: Record<string, TranslationKey> = {
  "Authentication required.": "errorAuthenticationRequired",
  "Unsupported action.": "errorUnsupportedAction",
  "Invalid answer.": "errorInvalidAnswer",
};

export function localizeServerError(
  locale: Locale,
  message: unknown,
  fallbackKey: TranslationKey,
) {
  if (typeof message !== "string") {
    return translate(locale, fallbackKey);
  }

  const key = serverErrorKeys[message];

  return key ? translate(locale, key) : message;
}

